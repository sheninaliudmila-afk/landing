  const focusNames = ['Движение денег', 'Прибыль и финансовая стратегия', 'Управленческая отчётность', 'Деньги бизнеса и собственника'];

  export function getResult(answers: number[]): QuizResult {
    if (!Array.isArray(answers) || answers.length !== questions.length ||
      answers.some((value) => !Number.isInteger(value) || value < 0 || value > 3) ||
      Object.keys(answers).filter((key) => /^\d+$/.test(key)).length !== questions.length) {
      throw new TypeError('Для результата нужно ответить на все 10 вопросов: выберите вариант от 0 до 3.');
    }
    const [stage, goal, reporting, cash, profit, plan, capital, team, preference, urgency] = answers as [number, number, number, number, number, number, number, number, number, number];
    const needsImplementation = reporting >= 2 || (reporting === 1 && team >= 1) || preference === 2 || (goal === 2 && reporting > 0);
    const needsStrategy = plan >= 2 || profit >= 2 || goal === 1 || stage >= 2 || preference === 1;
    const ongoing = preference === 3;
    const format: QuizResult['format'] = needsImplementation || ongoing ? 'support' : needsStrategy ? 'strategy' : 'diagnostic';
    const services: { title: string; description: string }[] = [];
    const add = (title: string, description: string) => {
      if (!services.some((service) => service.title === title)) services.push({ title, description });
    };

    const modules: Record<ModuleKey, () => void> = {
      cash: () => add('Движение денег и платёжный календарь', cash === 3
        ? 'Разобрать причины нехватки денег, приоритеты платежей и дебиторскую задолженность; составить платёжный календарь.'
        : 'Проверить поступления, обязательства и дебиторскую задолженность; связать их в понятный платёжный календарь.'),
      profit: () => add('Прибыльность и расходы', 'Рассчитать прибыль по направлениям, проверить структуру расходов и найти точки для повышения рентабельности.'),
      reporting: () => add('Управленческая отчётность', needsImplementation
        ? 'Настроить связанные отчёты ДДС, ОПиУ и баланс в 1С или Excel с учётом текущих данных и процессов.'
        : 'Проверить согласованность ДДС, ОПиУ и баланса, чтобы на отчёты можно было опираться в решениях.'),
      capital: () => add('Деньги собственника и бизнеса', 'Разделить личные и рабочие потоки, определить правила выплат собственнику и отметить вопросы для правовой и налоговой проверки.')
    };
    const priority = (['cash', 'profit', 'reporting', 'capital'] as const)[goal] ?? 'cash';
    modules[priority]();
    if (cash >= 1) modules['cash']();
    if (profit >= 1) modules['profit']();
    if (reporting >= 1 || needsImplementation) modules['reporting']();
    if (capital >= 1) modules['capital']();
    if (needsStrategy) add('Финансовая модель и стратегия', 'Связать цели бизнеса с расчётами: проверить сценарии, ресурсы, план доходов и расходов и последовательность действий.');
    if (needsImplementation && team >= 1) add('Передача системы и обучение', 'Распределить ответственность за данные, подготовить порядок обновления отчётов и обучить ответственных сотрудников.');
    if (ongoing) add('Ежемесячное сопровождение', 'Регулярно сопоставлять план и факт, отслеживать денежные потоки и обсуждать финансовые решения.');

    const reasons: string[] = [];
    reasons.push([
      'Ваш главный запрос — разобраться с денежными потоками и предстоящими платежами.',
      'Для вас в приоритете прибыльность и обоснованные решения для роста.',
      'Вам нужна понятная и достоверная система управленческих отчётов.',
      'Вы хотите прояснить отношения между деньгами бизнеса и деньгами собственника.'
    ][goal] ?? '');
    if (needsImplementation) reasons.push(reporting >= 2
      ? 'Управленческих отчётов пока недостаточно: после проверки данных стоит выстроить систему учёта.'
      : preference === 2 ? 'Вы хотите не только получить рекомендации, но и внедрить отчёты с передачей команде.'
        : 'Неполные отчёты и текущая организация учёта указывают на потребность в настройке системы.');
    if (needsStrategy) reasons.push(plan >= 2
      ? 'Цели пока не подкреплены полноценным финансовым планом — полезны модель и сценарии.'
      : profit >= 2 ? 'Нужно отделить прибыль от остатка денег и связать решения с расчётами.'
        : preference === 1 ? 'Вы предпочитаете получить стратегию и дальше двигаться по согласованному плану.'
          : 'Задачи роста требуют связать будущие решения с финансовой моделью.');
    if (ongoing) reasons.push('Вы выбрали регулярную поддержку, поэтому в маршрут включено ежемесячное сопровождение.');
    if (format === 'diagnostic') reasons.push('Базовые инструменты уже есть, а внедрение и постоянное сопровождение вы пока не запрашиваете.');

    const stages = [{ title: 'Финансовая диагностика', duration: '3–5 рабочих дней', description: 'Проверка исходных данных, разбор ситуации и согласование приоритетов. Следующие этапы уточняются по её итогам.' }];
    if (needsStrategy) stages.push({ title: 'Финансовая стратегия', duration: '1–2 недели', description: 'Финансовая модель, сценарии и план действий под задачи бизнеса.' });
    if (needsImplementation) stages.push({ title: 'Внедрение и обучение', duration: '2–4 недели', description: 'Настройка управленческих отчётов, проверка данных и передача процесса ответственным.' });
    if (ongoing) stages.push({ title: 'Регулярное сопровождение', duration: 'Ежемесячно', description: 'Контроль показателей и корректировка плана после завершения стартовых этапов.' });

    let title: string, duration: string, summary: string;
    if (format === 'diagnostic') {
      title = 'Финансовая диагностика';
      duration = '3–5 рабочих дней';
      summary = 'Начните с проверки финансовой картины и списка конкретных действий. По вашим ответам пока достаточно точечного разбора.';
    } else if (format === 'strategy') {
      title = 'Диагностика и финансовая стратегия';
      duration = '3–5 рабочих дней + 1–2 недели';
      summary = 'После проверки данных стоит связать ваши цели с финансовой моделью и подготовить последовательный план действий.';
    } else if (needsImplementation) {
      title = ongoing ? 'Внедрение с сопровождением' : 'Внедрение финансовой системы';
      duration = needsStrategy ? 'Диагностика + 3–6 недель' : 'Диагностика + 2–4 недели';
      if (ongoing) duration += ', затем ежемесячно';
      summary = 'Полезна поэтапная работа: проверить данные, настроить управленческую отчётность и передать понятные инструменты команде.';
    } else {
      title = 'Финансовое сопровождение';
      duration = needsStrategy ? 'Диагностика + 1–2 недели, затем ежемесячно' : '3–5 рабочих дней, затем ежемесячно';
      summary = 'Начните с проверки текущих данных, затем переходите к регулярному контролю показателей и поддержке финансовых решений.';
    }
    const scheduleNotes: string[] = [];
    if (urgency === 0) scheduleNotes.push('На старте выделим срочные платежи и решения. Экспресс-тест не заменяет проверку данных и не гарантирует завершение работы за неделю.');
    else if (urgency === 1) scheduleNotes.push('Можно планировать старт в ближайшие 2–4 недели после согласования задачи и подготовки данных.');
    else if (urgency === 2) scheduleNotes.push('До старта в течение 1–2 месяцев можно подготовить отчёты, выгрузки и список вопросов.');
    else scheduleNotes.push('Результат поможет спокойно выбрать следующий шаг; проходить все этапы сразу необязательно.');
    scheduleNotes.push('Сроки ориентировочные: точный объём и последовательность согласуются после диагностики. Длительность этапов указана отдельно и зависит от качества исходных данных.');
    return { format, title, duration, summary, reasons, services, stages, focus: focusNames[goal] ?? '', schedule: scheduleNotes.join(' ') };
  }
